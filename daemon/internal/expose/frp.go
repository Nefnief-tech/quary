// frp tunnel provider: one frpc container per exposed server. The client
// config is written under the servers root (a host-visible path by the
// compose contract) and bind-mounted read-only into the container; the
// frps endpoint and token come from the panel's provider settings.
package expose

import (
	"context"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/google/uuid"
)

// FrpStatus is the JSON-encoded command result.
type FrpStatus struct {
	Active  bool   `json:"active"`
	Address string `json:"address,omitempty"`
}

// FrpParams describes one frp mapping.
type FrpParams struct {
	ServerAddr string
	ServerPort int32
	Token      string
	RemotePort int32
	LocalPort  int32
}

// StartFrp writes the frpc config and starts the tunnel container.
func (m *Manager) StartFrp(ctx context.Context, id uuid.UUID, p FrpParams, emit Emitter) (*FrpStatus, error) {
	if p.ServerAddr == "" || p.Token == "" {
		return nil, fmt.Errorf("frp is not configured in the admin settings")
	}
	if p.RemotePort < 1024 || p.RemotePort > 65535 {
		return nil, fmt.Errorf("remote port must be between 1024 and 65535")
	}
	cfgPath, err := m.writeFrpConfig(id, p)
	if err != nil {
		return nil, err
	}
	if err := m.rt.EnsureFrpcImage(ctx); err != nil {
		return nil, err
	}
	if err := m.rt.StartFrpc(ctx, id, cfgPath); err != nil {
		return nil, err
	}
	if err := m.storeFrpMapping(id, p); err != nil {
		return nil, err
	}
	addr := fmt.Sprintf("%s:%d", p.ServerAddr, p.RemotePort)
	emitConsole(emit, id, "frp: tunnel live at "+addr)
	return &FrpStatus{Active: true, Address: addr}, nil
}

// writeFrpConfig renders the frpc TOML under the servers root. That path
// is host-visible by the compose contract, so the sibling container can
// bind-mount it.
func (m *Manager) writeFrpConfig(id uuid.UUID, p FrpParams) (string, error) {
	dir := filepath.Join(m.cfg.ServersRoot, ".frp")
	if err := os.MkdirAll(dir, 0o700); err != nil {
		return "", fmt.Errorf("create frp config dir: %w", err)
	}
	cfg := fmt.Sprintf(`# Generated by Quarry; do not edit (overwritten on tunnel updates)
serverAddr = %q
serverPort = %d
auth.token = %q
loginFailExit = false

[[proxies]]
name = "quarry-%s"
type = "tcp"
localIP = "127.0.0.1"
localPort = %d
remotePort = %d
`, p.ServerAddr, p.ServerPort, p.Token, id.String()[:8], p.LocalPort, p.RemotePort)
	path := filepath.Join(dir, id.String()+".toml")
	if err := os.WriteFile(path, []byte(cfg), 0o600); err != nil {
		return "", fmt.Errorf("write frpc config: %w", err)
	}
	return path, nil
}

func (m *Manager) frpMappingPath(id uuid.UUID) string {
	return m.cfg.DataDir + "/frp-" + id.String() + ".json"
}

func (m *Manager) storeFrpMapping(id uuid.UUID, p FrpParams) error {
	return os.WriteFile(m.frpMappingPath(id), []byte(fmt.Sprintf(`{"remote_port":%d}`, p.RemotePort)), 0o600)
}

// StopFrp removes the tunnel container and forgets the mapping.
func (m *Manager) StopFrp(ctx context.Context, id uuid.UUID, emit Emitter) error {
	_ = m.rt.StopFrpc(ctx, id)
	_ = os.Remove(filepath.Join(m.cfg.ServersRoot, ".frp", id.String()+".toml"))
	_ = os.Remove(m.frpMappingPath(id))
	emitConsole(emit, id, "frp: tunnel stopped")
	return nil
}

// ReconcileFrp restarts frpc containers whose config and mapping survived
// a daemon restart.
func (m *Manager) ReconcileFrp(ctx context.Context) {
	files, err := filepath.Glob(filepath.Join(m.cfg.ServersRoot, ".frp", "*.toml"))
	if err != nil {
		return
	}
	for _, f := range files {
		base := strings.TrimSuffix(filepath.Base(f), ".toml")
		id, err := uuid.Parse(base)
		if err != nil {
			continue
		}
		if _, err := os.Stat(m.frpMappingPath(id)); err != nil {
			continue
		}
		running, err := m.rt.FrpcRunning(ctx, id)
		if err == nil && running {
			continue
		}
		if err := m.rt.StartFrpc(ctx, id, f); err != nil {
			m.log.Warn("frpc restart failed", "server_id", id, "err", err)
		}
	}
}
